// Writes testvectors/base94max.json from the JavaScript implementation, so the
// Rust port can be checked against the encoder that defines the format rather
// than against a second reading of the specification.
//
//     node tools/gen-testvectors.js
//
// Deterministic: every input is derived from a fixed formula or a seeded PRNG,
// so a rerun either produces the same file or something has changed.

import { writeFileSync } from 'fs';
import Base94Max from '../index.js';

// xorshift32, so the sequence is reproducible without a dependency and can be
// restated in any language that needs to regenerate this file.
function prng(seed) {
    let s = seed >>> 0;
    return () => {
        s ^= s << 13; s >>>= 0;
        s ^= s >>> 17;
        s ^= s << 5;  s >>>= 0;
        return s & 0xff;
    };
}

function seeded(len, seed) {
    const next = prng(seed);
    return new Uint8Array(Array.from({ length: len }, next));
}

const cases = [];
const add = (name, data) => cases.push({
    name,
    input: Buffer.from(data).toString('hex'),
    encoded: Base94Max.encode(data),
});

// Block boundaries. The encoder consumes 13 or 14 bits at a time, so the
// interesting lengths are the ones around where a block closes and where the
// trailing partial block takes each of its branches.
for (let n = 0; n <= 24; n++) {
    add(`len ${n}, zeros`, new Uint8Array(n));
    add(`len ${n}, 0xff`, new Uint8Array(n).fill(0xff));
    add(`len ${n}, counting`, new Uint8Array(Array.from({ length: n }, (_, i) => i & 0xff)));
    add(`len ${n}, seeded`, seeded(n, 0x9e3779b9 ^ n));
}

// Every byte value, and the patterns that drive the 13/14-bit decision to one
// side or the other.
add('all byte values', new Uint8Array(Array.from({ length: 256 }, (_, i) => i)));
add('alternating 00/ff', new Uint8Array(Array.from({ length: 64 }, (_, i) => (i & 1) ? 0xff : 0x00)));
add('alternating 55/aa', new Uint8Array(Array.from({ length: 64 }, (_, i) => (i & 1) ? 0xaa : 0x55)));
add('low nibbles', new Uint8Array(Array.from({ length: 64 }, (_, i) => i & 0x0f)));
add('high bits set', new Uint8Array(Array.from({ length: 64 }, () => 0x80)));

// Longer seeded runs, where the adaptive branch is taken many times.
for (const len of [100, 255, 256, 257, 1000, 4096, 8192]) {
    add(`len ${len}, seeded`, seeded(len, 0x243f6a88 ^ len));
}

// Text, which is what a caller most often hands this encoder.
for (const s of ['Hello', 'Man', 'Test!', '<>?/', 'The quick brown fox jumps over the lazy dog']) {
    add(`text ${JSON.stringify(s)}`, new TextEncoder().encode(s));
}

const out = {
    note: 'Generated by tools/gen-testvectors.js from index.js. Do not edit by hand.',
    alphabet: 'PRINTABLE',
    cases,
};
writeFileSync(new URL('../testvectors/base94max.json', import.meta.url),
    JSON.stringify(out, null, 2) + '\n');
console.log(`${cases.length} cases written`);
